/**
 * 모호한 지역명인지 확인
 */
export function isAmbiguousRegion(region: string): boolean {
  return region.trim() in AMBIGUOUS_REGIONS;
}

/**
 * 모호한 지역명에 대한 안내 메시지 반환
 */
export function getAmbiguousRegionMessage(region: string): string | null {
  const info = AMBIGUOUS_REGIONS[region.trim()];
  return info?.message ?? null;
}

/**
 * 지역명 정규화
 * 축약어를 정식명으로 변환, 없으면 원본 반환
 */
export function normalizeRegionName(input: string): string {
  const trimmed = input.trim();

  if (REGION_ALIASES[trimmed]) {
    return REGION_ALIASES[trimmed];
  }

  return trimmed;
}

/**
 * 여러 지역명 정규화
 */
export function normalizeRegionNames(regions: string[]): string[] {
  return regions.map(normalizeRegionName);
}
