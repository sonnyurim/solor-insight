/**
 * 동의어를 표준어로 변환하는 맵 생성
 * { 동의어: 표준어 } 형태
 */
export function createSynonymMap(): Map<string, string> {
  const map = new Map<string, string>();

  for (const [standard, synonyms] of Object.entries(SYNONYMS)) {
    for (const synonym of synonyms) {
      map.set(synonym, standard);
    }
  }

  return map;
}

